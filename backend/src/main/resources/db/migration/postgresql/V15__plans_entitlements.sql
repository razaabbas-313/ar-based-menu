CREATE TABLE entitlement_plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, description VARCHAR(1000) NOT NULL,
 active BOOLEAN NOT NULL, version BIGINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE entitlement_plan_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plan_id BIGINT NOT NULL REFERENCES entitlement_plans(id),
 revision BIGINT NOT NULL, name VARCHAR(100) NOT NULL, description VARCHAR(1000) NOT NULL,
 values_json TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(plan_id,revision)
);
CREATE TABLE restaurant_entitlement_policy (
 restaurant_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
 revision_id BIGINT REFERENCES entitlement_plan_revisions(id),
 version BIGINT NOT NULL DEFAULT 0
);
INSERT INTO restaurant_entitlement_policy(restaurant_id,version) SELECT id,0 FROM restaurants;
CREATE TABLE restaurant_entitlement_overrides (
 restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
 feature_key VARCHAR(80) NOT NULL, value_json TEXT NOT NULL,
 reason VARCHAR(500) NOT NULL, actor_id BIGINT NOT NULL,
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE,
 PRIMARY KEY(restaurant_id,feature_key),
 CHECK(expires_at IS NULL OR expires_at>starts_at)
);
CREATE TABLE entitlement_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_id BIGINT, plan_id BIGINT, actor_id BIGINT NOT NULL,
 actor_email VARCHAR(160) NOT NULL, action VARCHAR(40) NOT NULL,
 feature_key VARCHAR(80), before_json TEXT NOT NULL, after_json TEXT NOT NULL,
 reason VARCHAR(500) NOT NULL, expires_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_entitlement_audit_tenant ON entitlement_audit(restaurant_id,id);
CREATE INDEX idx_entitlement_audit_plan ON entitlement_audit(plan_id,id);
CREATE INDEX idx_entitlement_override_expiry ON restaurant_entitlement_overrides(expires_at);
CREATE INDEX idx_entitlement_policy_revision ON restaurant_entitlement_policy(revision_id);
CREATE TABLE entitlement_request_usage (
 operation_id VARCHAR(64) PRIMARY KEY,
 restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
 dish_id BIGINT NOT NULL, submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
INSERT INTO entitlement_request_usage(operation_id,restaurant_id,dish_id,submitted_at)
 SELECT CONCAT('legacy-',CAST(id AS VARCHAR)),restaurant_id,dish_id,requested_at FROM model_requests;
CREATE INDEX idx_entitlement_request_period ON entitlement_request_usage(restaurant_id,submitted_at);
