-- H2 equivalent of db/migration/postgresql/V2 (local profile).
-- H2 databases are always created by this codebase, so media_details is empty when V2 runs and
-- no legacy backfill is needed. H2 has no partial indexes; the menu index includes the status.

CREATE TABLE IF NOT EXISTS restaurants (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    slug          VARCHAR(60)  NOT NULL,
    owner_name    VARCHAR(120) NOT NULL,
    email         VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_restaurants_slug  UNIQUE (slug),
    CONSTRAINT uq_restaurants_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_restaurants_slug ON restaurants (slug);

ALTER TABLE media_details ADD COLUMN restaurant_id BIGINT;
ALTER TABLE media_details ALTER COLUMN restaurant_id SET NOT NULL;
ALTER TABLE media_details ADD CONSTRAINT fk_media_details_restaurant
    FOREIGN KEY (restaurant_id) REFERENCES restaurants (id) ON DELETE CASCADE;
ALTER TABLE media_details ADD COLUMN version BIGINT DEFAULT 0 NOT NULL;

CREATE INDEX IF NOT EXISTS idx_media_details_restaurant_status ON media_details (restaurant_id, upload_status);

DROP INDEX IF EXISTS idx_media_details_menu;
CREATE INDEX IF NOT EXISTS idx_media_details_menu ON media_details (restaurant_id, upload_status, created_at DESC);
