CREATE TABLE restaurant_guest_settings (
 restaurant_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 0,
 menu_mode VARCHAR(16) NOT NULL DEFAULT 'LEGACY' CHECK(menu_mode IN ('LEGACY','SIMPLE','THREE_D','AR')),
 ordering_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 waiter_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 order_number VARCHAR(15), waiter_number VARCHAR(15),
 waiter_message VARCHAR(160) NOT NULL DEFAULT 'Please assist us.'
);
INSERT INTO restaurant_guest_settings(restaurant_id) SELECT id FROM restaurants;
CREATE TABLE restaurant_tables (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
 name VARCHAR(60) NOT NULL, normalized_name VARCHAR(60) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 qr_token VARCHAR(43) NOT NULL, token_hash VARCHAR(64) NOT NULL UNIQUE,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(restaurant_id,normalized_name)
);
CREATE INDEX idx_restaurant_tables_active ON restaurant_tables(restaurant_id,active,id);
