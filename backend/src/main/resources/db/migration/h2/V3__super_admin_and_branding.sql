-- ---------------------------------------------------------------- media_details (rebuild)
CREATE TABLE media_details_v3 (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id              BIGINT         NOT NULL,
    version                    BIGINT         DEFAULT 0 NOT NULL,
    original_file_name         VARCHAR(255)   NOT NULL,
    stored_file_name           VARCHAR(120)   NOT NULL,
    s3_bucket                  VARCHAR(63)    NOT NULL,
    s3_key                     VARCHAR(512)   NOT NULL,
    s3_url                     VARCHAR(1024)  NOT NULL,
    content_type               VARCHAR(64)    NOT NULL,
    file_extension             VARCHAR(10)    NOT NULL,
    file_size_bytes            BIGINT         NOT NULL,
    original_size_bytes        BIGINT,
    media_type                 VARCHAR(20)    NOT NULL,
    upload_status              VARCHAR(20)    DEFAULT 'PRESIGNED' NOT NULL,
    dish_title                 VARCHAR(160)   NOT NULL,
    price_tag                  NUMERIC(10, 2) NOT NULL,
    dish_category              VARCHAR(20)    NOT NULL,
    has_ar_support             BOOLEAN        DEFAULT FALSE NOT NULL,
    ar_placement               VARCHAR(10)    DEFAULT 'table' NOT NULL,
    width_px                   INTEGER,
    height_px                  INTEGER,
    etag                       VARCHAR(128),
    uploaded_by_user_id        VARCHAR(64),
    created_at                 TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at               TIMESTAMP WITH TIME ZONE,
    model_s3_key               VARCHAR(500),
    model_s3_url               VARCHAR(2048),
    model_file_size_bytes      BIGINT         DEFAULT 0 NOT NULL,
    pending_model_s3_key       VARCHAR(500),
    pending_model_size_bytes   BIGINT,
    pending_model_content_type VARCHAR(64),
    pending_model_created_at   TIMESTAMP WITH TIME ZONE,
    is_available               BOOLEAN        DEFAULT TRUE NOT NULL,
    description                VARCHAR(4000),
    dietary_tags               VARCHAR(255),
    CONSTRAINT uq_media_v3_s3_key UNIQUE (s3_key),
    CONSTRAINT uq_media_v3_model_s3_key UNIQUE (model_s3_key),
    CONSTRAINT fk_media_v3_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants (id) ON DELETE CASCADE,
    CONSTRAINT ck_media_v3_media_type CHECK (media_type IN ('IMAGE_2D', 'MODEL_3D', 'DAILY_SPECIAL')),
    CONSTRAINT ck_media_v3_upload_status CHECK (upload_status IN ('PRESIGNED', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_media_v3_dish_category CHECK (dish_category IN ('STARTERS', 'MAINS', 'DESSERTS', 'CHEF_SPECIALS', 'DRINKS')),
    CONSTRAINT ck_media_v3_ar_placement CHECK (ar_placement IN ('table', 'floor')),
    CONSTRAINT ck_media_v3_completed_at CHECK (upload_status <> 'COMPLETED' OR completed_at IS NOT NULL)
);

INSERT INTO media_details_v3 (restaurant_id, version, original_file_name, stored_file_name, s3_bucket, s3_key, s3_url,
                              content_type, file_extension, file_size_bytes, original_size_bytes, media_type, upload_status,
                              dish_title, price_tag, dish_category, has_ar_support, ar_placement, width_px, height_px, etag,
                              uploaded_by_user_id, created_at, completed_at, model_s3_key, model_s3_url, model_file_size_bytes)
SELECT restaurant_id, version, original_file_name, stored_file_name, s3_bucket, s3_key, s3_url,
       content_type, file_extension, file_size_bytes, original_size_bytes, media_type, upload_status,
       dish_title, price_tag, dish_category, has_ar_support, ar_placement, width_px, height_px, etag,
       uploaded_by_user_id, created_at, completed_at,
       CASE WHEN content_type LIKE 'model/%' THEN s3_key END,
       CASE WHEN content_type LIKE 'model/%' THEN s3_url END,
       CASE WHEN content_type LIKE 'model/%' THEN file_size_bytes ELSE 0 END
  FROM media_details;

DROP TABLE media_details;
ALTER TABLE media_details_v3 RENAME TO media_details;

CREATE INDEX IF NOT EXISTS idx_media_details_upload_status ON media_details (upload_status);
CREATE INDEX IF NOT EXISTS idx_media_details_dish_category ON media_details (dish_category);
CREATE INDEX IF NOT EXISTS idx_media_details_media_type ON media_details (media_type);
CREATE INDEX IF NOT EXISTS idx_media_details_created_at ON media_details (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_media_details_restaurant_status ON media_details (restaurant_id, upload_status);
CREATE INDEX IF NOT EXISTS idx_media_details_menu ON media_details (restaurant_id, upload_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_media_details_public_menu ON media_details (restaurant_id, is_available, created_at DESC);

UPDATE restaurants r
   SET dish_count = (SELECT COUNT(*) FROM media_details m WHERE m.restaurant_id = r.id AND m.upload_status = 'COMPLETED'),
       model_3d_count = (SELECT COUNT(*) FROM media_details m WHERE m.restaurant_id = r.id AND m.upload_status = 'COMPLETED' AND m.model_s3_key IS NOT NULL),
       storage_used_bytes = (SELECT COALESCE(SUM(CASE WHEN m.content_type LIKE 'model/%' THEN 0 ELSE m.file_size_bytes END + m.model_file_size_bytes), 0)
                               FROM media_details m WHERE m.restaurant_id = r.id AND m.upload_status = 'COMPLETED');

