CREATE TABLE model_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_id BIGINT NOT NULL, dish_id BIGINT NOT NULL,
 version_number BIGINT NOT NULL, object_key VARCHAR(1024) NOT NULL,
 object_url TEXT, size_bytes BIGINT NOT NULL,
 origin VARCHAR(32) NOT NULL, actor_kind VARCHAR(32), actor_id BIGINT,
 request_id BIGINT, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 published_at TIMESTAMP WITH TIME ZONE, state VARCHAR(20) NOT NULL,
 retention VARCHAR(24) NOT NULL DEFAULT 'HELD', availability VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED',
 UNIQUE(dish_id,version_number), UNIQUE(dish_id,object_key)
);
CREATE INDEX idx_model_versions_tenant ON model_versions(restaurant_id,dish_id,id);
CREATE INDEX idx_model_versions_retained ON model_versions(object_key,retention);
INSERT INTO model_versions(restaurant_id,dish_id,version_number,object_key,object_url,size_bytes,origin,state)
 SELECT restaurant_id,id,1,model_s3_key,model_s3_url,COALESCE(model_file_size_bytes,0),'LEGACY_UNKNOWN','CURRENT'
 FROM media_details WHERE model_s3_key IS NOT NULL;
CREATE TABLE restaurant_appearance (
 restaurant_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 0, draft_json TEXT, published_json TEXT,
 published_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE restaurant_reviews (
 restaurant_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 0, destination VARCHAR(600), enabled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE guest_insight_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
 event_id VARCHAR(36) NOT NULL, event_type VARCHAR(40) NOT NULL,
 dish_id BIGINT, category_key VARCHAR(80), menu_mode VARCHAR(16) NOT NULL,
 entry_context VARCHAR(16) NOT NULL, received_day DATE NOT NULL, received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(restaurant_id,event_id)
);
CREATE INDEX idx_guest_insight_range ON guest_insight_events(restaurant_id,received_day,event_type);

CREATE TABLE analytics_legacy_dedup (dedup_key VARCHAR(64) PRIMARY KEY, expires_at TIMESTAMP WITH TIME ZONE NOT NULL);
CREATE TABLE brand_studio_assets (
 id VARCHAR(36) PRIMARY KEY, restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
 object_key VARCHAR(1024) NOT NULL UNIQUE, upload_key VARCHAR(1024), object_url TEXT NOT NULL,
 purpose VARCHAR(16) NOT NULL, expected_bytes BIGINT NOT NULL, content_type VARCHAR(100) NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'ISSUED', expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_brand_studio_assets_tenant ON brand_studio_assets(restaurant_id,created_at);
CREATE TABLE model_upload_issuances (
 object_key VARCHAR(1024) PRIMARY KEY, restaurant_id BIGINT NOT NULL, dish_id BIGINT NOT NULL,
