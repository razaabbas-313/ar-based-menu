CREATE TABLE IF NOT EXISTS model_requests (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id        BIGINT       NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    dish_id              BIGINT       NOT NULL REFERENCES media_details(id) ON DELETE CASCADE,
    status               VARCHAR(30)  NOT NULL DEFAULT 'PENDING',
    request_type         VARCHAR(30)  NOT NULL DEFAULT 'NEW',
    reference_photos     TEXT,
    notes                TEXT,
    admin_notes          TEXT,
    completed_model_key  VARCHAR(512),
    completed_model_url  VARCHAR(1024),
    requested_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at         TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_model_requests_dish ON model_requests (dish_id, status);
CREATE INDEX IF NOT EXISTS idx_model_requests_restaurant ON model_requests (restaurant_id, requested_at DESC);
CREATE INDEX IF NOT EXISTS idx_model_requests_status ON model_requests (status, requested_at DESC);

-- Backfill existing pending/completed requests from media_details
INSERT INTO model_requests (restaurant_id, dish_id, status, request_type, reference_photos, notes, completed_model_key, completed_model_url, requested_at, completed_at)
SELECT
    m.restaurant_id,
    m.id,
    CASE 
        WHEN m.model_request_status = 'COMPLETED' THEN 'COMPLETED'
        WHEN m.model_request_status = 'PENDING' THEN 'PENDING'
        WHEN m.model_request_status = 'IN_PRODUCTION' THEN 'IN_PRODUCTION'
        ELSE 'PENDING'
    END,
    CASE WHEN m.has_ar_support = TRUE THEN 'REPLACEMENT' ELSE 'NEW' END,
    m.model_request_photos,
    m.model_request_notes,
    m.model_s3_key,
    m.model_s3_url,
    COALESCE(m.model_requested_at, m.created_at),
    m.model_completed_at
FROM media_details m
WHERE m.model_request_status IS NOT NULL 
  AND m.model_request_status NOT IN ('NONE', '');
